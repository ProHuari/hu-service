package com.huariservice.huariia.services;

import com.huariservice.huariia.dto.AiHistoryResponse;
import com.huariservice.huariia.entities.AiHistory;
import com.huariservice.huariia.entities.User;
import com.huariservice.huariia.exceptions.RecursoNaoEncontradoException;
import com.huariservice.huariia.repositories.AiHistoryRepository;
import com.huariservice.huariia.repositories.UserRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;

/**
 * Business logic for persisting and querying {@link AiHistory} records.
 *
 * <p>History records are append-only; queried dates are auto-generated.
 * Regular students can only access their own history; admins can view all records.</p>
 */
@Service
@Transactional
@RequiredArgsConstructor
public class AiHistoryService {

    private final AiHistoryRepository historyRepository;
    private final UserRepository userRepository;

    /**
     * Persists a newly generated question-and-answer exchange.
     *
     * @param userId   the ID of the authenticated user
     * @param question prompt text sent by the user
     * @param answer   answer generated by the AI
     * @return the saved entry as a response DTO
     * @throws RecursoNaoEncontradoException if the user does not exist
     */
    public AiHistoryResponse saveHistory(Long userId, String question, String answer) {
        User user = userRepository.findById(userId)
                .orElseThrow(() -> new RecursoNaoEncontradoException("User not found"));

        AiHistory history = new AiHistory();
        history.setQuestion(question);
        history.setAnswer(answer);
        history.setUser(user);

        return AiHistoryResponse.from(historyRepository.save(history));
    }

    /**
     * Lists all AI history entries (administrator view).
     *
     * @return list of all history responses
     */
    @Transactional(readOnly = true)
    public List<AiHistoryResponse> listAllHistory() {
        return historyRepository.findAll().stream().map(AiHistoryResponse::from).toList();
    }

    /**
     * Lists the history of a specific user, sorted from most recent to oldest.
     *
     * @param userId user identifier
     * @return the user's history responses
     */
    @Transactional(readOnly = true)
    public List<AiHistoryResponse> listHistoryByUser(Long userId) {
        return historyRepository.findByUserIdOrderByQueriedAtDesc(userId).stream()
                .map(AiHistoryResponse::from).toList();
    }

    /**
     * Retrieves a single history entry by ID, enforcing ownership restrictions.
     *
     * @param id      history record identifier
     * @param userId  authenticated user ID
     * @param isAdmin whether the caller is an administrator
     * @return the history response DTO
     * @throws RecursoNaoEncontradoException if not found or unauthorized
     */
    @Transactional(readOnly = true)
    public AiHistoryResponse findById(Long id, Long userId, boolean isAdmin) {
        return AiHistoryResponse.from(findHistoryOrThrow(id, userId, isAdmin));
    }

    /**
     * Deletes a history entry by ID, enforcing ownership restrictions.
     *
     * @param id      history record identifier
     * @param userId  authenticated user ID
     * @param isAdmin whether the caller is an administrator
     * @throws RecursoNaoEncontradoException if not found or unauthorized
     */
    public void deleteById(Long id, Long userId, boolean isAdmin) {
        historyRepository.delete(findHistoryOrThrow(id, userId, isAdmin));
    }

    /**
     * Finds a history entry and checks ownership. Returns 404 rather than 403
     * to avoid leaking resource existence.
     */
    private AiHistory findHistoryOrThrow(Long id, Long userId, boolean isAdmin) {
        AiHistory history = historyRepository.findById(id)
                .orElseThrow(() -> new RecursoNaoEncontradoException("AI history not found"));

        if (!isAdmin && !history.getUser().getId().equals(userId)) {
            throw new RecursoNaoEncontradoException("AI history not found");
        }
        return history;
    }
}