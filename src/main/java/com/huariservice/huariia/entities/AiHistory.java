package com.huariservice.huariia.entities;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.ToString;

import java.time.LocalDateTime;

/**
 * JPA entity that stores each question a {@link User} asked the AI assistant together with
 * the generated answer.
 *
 * <p>Mapped to the legacy table {@code historico_ia}. The composite index on
 * ({@code usuario_id}, {@code data_consulta}) supports listing a user's history ordered by date.</p>
 */
@Entity
@Table(name = "historico_ia", indexes = {
        @Index(name = "idx_historico_ia_usuario_data", columnList = "usuario_id, data_consulta")
})
@Data
@AllArgsConstructor
@NoArgsConstructor
public class AiHistory {

    /** Surrogate primary key generated by the database. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @ToString.Include
    private Long id;

    /** The prompt/question sent by the user. */
    @Column(name = "pergunta", columnDefinition = "TEXT", nullable = false)
    private String question;

    /** The answer returned by the AI provider. */
    @Column(name = "resposta", columnDefinition = "TEXT", nullable = false)
    private String answer;

    /** When the query happened; immutable after insert. */
    @Column(name = "data_consulta", nullable = false, updatable = false)
    private LocalDateTime queriedAt;

    /** The user who made the query (loaded lazily). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "usuario_id", nullable = false)
    @ToString.Exclude
    private User user;

    /**
     * JPA callback executed before the first INSERT.
     * Defaults {@link #queriedAt} to "now" when the caller did not set it explicitly.
     */
    @PrePersist
    void onCreate() {
        if (queriedAt == null) {
            this.queriedAt = LocalDateTime.now();
        }
    }

    /** Identity-based equality: equal only when both instances are persisted with the same id. */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof AiHistory other)) return false;
        return id != null && id.equals(other.id);
    }

    /** Constant class-based hash, stable before and after the id is generated. */
    @Override
    public int hashCode() {
        return getClass().hashCode();
    }
}
