package com.huariservice.huariia.entities;

import jakarta.persistence.*;
import jakarta.validation.constraints.Min;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.ToString;

/**
 * JPA entity representing a single video lesson that belongs to a {@link CourseModule}.
 *
 * <p>Mapped to the legacy table {@code aulas}; the unique constraint guarantees that two
 * lessons of the same module never share the same position.</p>
 */
@Entity
@Table(name = "aulas", uniqueConstraints = {
        @UniqueConstraint(columnNames = {"modulo_id", "ordem"})
})
@Data
@AllArgsConstructor
@NoArgsConstructor
public class Lesson {

    /** Surrogate primary key generated by the database. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @ToString.Include
    private Long id;

    /** Lesson title. */
    @Column(name = "titulo", length = 155, nullable = false)
    @ToString.Include
    private String title;

    /** Lesson description / summary. */
    @Column(name = "descricao", columnDefinition = "TEXT", nullable = false)
    private String description;

    /** Unique URL of the lesson video. */
    @Column(name = "url_video", length = 254, nullable = false, unique = true)
    private String videoUrl;

    /** 1-based display position inside the module (legacy column {@code ordem}). */
    @Min(1)
    @Column(name = "ordem", nullable = false)
    private Integer position;

    /** Optional video length in minutes; never negative. */
    @Min(0)
    @Column(name = "duracao_em_minutos")
    private Integer durationInMinutes;

    /** Owning module (loaded lazily). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "modulo_id", nullable = false)
    @ToString.Exclude
    private CourseModule module;

    /** Identity-based equality: equal only when both instances are persisted with the same id. */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Lesson other)) return false;
        return id != null && id.equals(other.id);
    }

    /** Constant class-based hash, stable before and after the id is generated. */
    @Override
    public int hashCode() {
        return getClass().hashCode();
    }
}
