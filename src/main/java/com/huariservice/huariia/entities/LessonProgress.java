package com.huariservice.huariia.entities;

import com.huariservice.huariia.entities.enums.LessonStatus;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.ToString;

import java.time.LocalDateTime;

/**
 * JPA entity that tracks how far a given {@link User} has progressed in a given {@link Lesson}.
 *
 * <p>Mapped to the legacy table {@code progresso_aula}. There is at most one row per
 * (user, lesson) pair, enforced by a unique constraint; both foreign keys are indexed for
 * fast "progress of this user" and "progress of this lesson" queries.</p>
 */
@Entity
@Table(name = "progresso_aula", uniqueConstraints = {
        @UniqueConstraint(columnNames = {"usuario_id", "aula_id"})
}, indexes = {
        @Index(name = "idx_progresso_usuario", columnList = "usuario_id"),
        @Index(name = "idx_progresso_aula", columnList = "aula_id")
})
@Data
@AllArgsConstructor
@NoArgsConstructor
public class LessonProgress {

    /** Surrogate primary key generated by the database. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @ToString.Include
    private Long id;

    /** Current progress state; starts as {@link LessonStatus#NOT_STARTED}. */
    @Enumerated(EnumType.STRING)
    @Column(name = "status_aula", nullable = false)
    @ToString.Include
    private LessonStatus status = LessonStatus.NOT_STARTED;

    /** Completion timestamp; only filled when {@link #status} is {@link LessonStatus#COMPLETED}. */
    @Column(name = "data_conclusao")
    private LocalDateTime completedAt;

    /** The learner this progress belongs to (loaded lazily). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "usuario_id", nullable = false)
    @ToString.Exclude
    private User user;

    /** The lesson being tracked (loaded lazily). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "aula_id", nullable = false)
    @ToString.Exclude
    private Lesson lesson;

    /**
     * Marks the lesson as finished.
     * <ol>
     *   <li>Sets {@link #status} to {@link LessonStatus#COMPLETED}.</li>
     *   <li>Records the current date/time in {@link #completedAt}.</li>
     * </ol>
     */
    public void complete() {
        this.status = LessonStatus.COMPLETED;
        this.completedAt = LocalDateTime.now();
    }

    /** Identity-based equality: equal only when both instances are persisted with the same id. */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof LessonProgress other)) return false;
        return id != null && id.equals(other.id);
    }

    /** Constant class-based hash, stable before and after the id is generated. */
    @Override
    public int hashCode() {
        return getClass().hashCode();
    }
}
