package com.huariservice.huariia.entities;

import com.huariservice.huariia.entities.enums.Role;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.ToString;

import java.time.LocalDateTime;
import java.util.Locale;

/**
 * JPA entity representing a platform account (student or administrator).
 *
 * <p>Mapped to the legacy Portuguese table {@code usuarios}; every renamed field keeps its
 * original column name through {@link Column#name()}, so no schema change is required.
 * Keeping the table name also avoids {@code user}, which is a reserved word in several databases.</p>
 */
@Entity
@Table(name = "usuarios")
@Data
@AllArgsConstructor
@NoArgsConstructor
public class User {

    /** Surrogate primary key generated by the database (auto-increment). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @ToString.Include
    private Long id;

    /** Display name of the user. */
    @Column(name = "nome", length = 100, nullable = false)
    @ToString.Include
    private String name;

    /** Unique login e-mail, always stored trimmed and lower-cased (see {@link #normalizeEmail()}). */
    @Column(length = 100, nullable = false, unique = true)
    @ToString.Include
    private String email;

    /** BCrypt hash of the password (60 chars). The plain-text password is never stored. */
    @Column(name = "senha_hash", length = 60, nullable = false)
    private String passwordHash;

    /** Authorization role; new accounts are students by default. */
    @Enumerated(EnumType.STRING)
    @Column(name = "tipo_perfil", nullable = false)
    private Role role = Role.STUDENT;

    /** Timestamp of account creation; set once and never updated. */
    @Column(name = "criado_em", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    /**
     * JPA lifecycle callback executed right before the first INSERT.
     * <ol>
     *   <li>Stamps {@link #createdAt} with the current date/time.</li>
     *   <li>Normalizes the e-mail so uniqueness checks are case-insensitive.</li>
     * </ol>
     */
    @PrePersist
    void onCreate() {
        this.createdAt = LocalDateTime.now();
        normalizeEmail();
    }

    /**
     * JPA lifecycle callback executed before every UPDATE.
     * Re-normalizes the e-mail in case it was changed.
     */
    @PreUpdate
    void onUpdate() {
        normalizeEmail();
    }

    /**
     * Trims surrounding whitespace and converts the e-mail to lower case using
     * {@link Locale#ROOT} (locale-independent). Does nothing if the e-mail is {@code null}.
     */
    private void normalizeEmail() {
        if (email != null) {
            this.email = email.trim().toLowerCase(Locale.ROOT);
        }
    }

    /**
     * Identity-based equality: two users are equal only if both are persisted and share the same id.
     * Transient (unsaved) instances are never equal to each other.
     */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof User other)) return false;
        return id != null && id.equals(other.id);
    }

    /**
     * Returns a class-based constant hash so the value does not change when the id is
     * assigned after persisting (keeps the entity stable inside hash-based collections).
     */
    @Override
    public int hashCode() {
        return getClass().hashCode();
    }
}
