package com.huariservice.huariia.entities;

import com.huariservice.huariia.entities.enums.EnrollmentStatus;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.ToString;

import java.time.LocalDate;

/**
 * JPA entity representing the enrollment of a {@link User} in a {@link Course}.
 *
 * <p>Mapped to the legacy table {@code matriculas}. A user can be enrolled only once per
 * course (unique constraint). Indexes speed up "my courses" (by user) and
 * "enrolled students" (by course) queries.</p>
 */
@Entity
@Table(name = "matriculas", uniqueConstraints = {
        @UniqueConstraint(columnNames = {"usuario_id", "curso_id"})
}, indexes = {
        @Index(name = "idx_matricula_usuario", columnList = "usuario_id"),
        @Index(name = "idx_matricula_curso", columnList = "curso_id")
})
@Data
@AllArgsConstructor
@NoArgsConstructor
public class Enrollment {

    /** Surrogate primary key generated by the database. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @ToString.Include
    private Long id;

    /** Date the enrollment was created; immutable after insert. */
    @Column(name = "data_matricula", nullable = false, updatable = false)
    private LocalDate enrollmentDate;

    /** Current lifecycle state; starts as {@link EnrollmentStatus#ACTIVE}. */
    @Enumerated(EnumType.STRING)
    @Column(name = "status_matricula", nullable = false)
    @ToString.Include
    private EnrollmentStatus status = EnrollmentStatus.ACTIVE;

    /** The enrolled learner (loaded lazily). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "usuario_id", nullable = false)
    @ToString.Exclude
    private User user;

    /** The course the learner is enrolled in (loaded lazily). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "curso_id", nullable = false)
    @ToString.Exclude
    private Course course;

    /**
     * JPA callback executed before the first INSERT.
     * Defaults {@link #enrollmentDate} to today when the caller did not provide one.
     */
    @PrePersist
    void onCreate() {
        if (enrollmentDate == null) {
            this.enrollmentDate = LocalDate.now();
        }
    }

    /** Identity-based equality: equal only when both instances are persisted with the same id. */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Enrollment other)) return false;
        return id != null && id.equals(other.id);
    }

    /** Constant class-based hash, stable before and after the id is generated. */
    @Override
    public int hashCode() {
        return getClass().hashCode();
    }
}
