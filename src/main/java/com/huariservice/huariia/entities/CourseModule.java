package com.huariservice.huariia.entities;

import jakarta.persistence.*;
import jakarta.validation.constraints.Min;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.ToString;

/**
 * JPA entity representing an ordered section of a {@link Course} that groups related lessons.
 *
 * <p>Named {@code CourseModule} (instead of {@code Module}) to avoid clashing with
 * {@link java.lang.Module}. Mapped to the legacy table {@code modulos}; the unique constraint
 * guarantees that two modules of the same course never share the same position.</p>
 */
@Entity
@Table(name = "modulos", uniqueConstraints = {
        @UniqueConstraint(columnNames = {"curso_id", "ordem"})
})
@Data
@AllArgsConstructor
@NoArgsConstructor
public class CourseModule {

    /** Surrogate primary key generated by the database. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @ToString.Include
    private Long id;

    /** Module title. */
    @Column(name = "titulo", length = 150, nullable = false)
    @ToString.Include
    private String title;

    /** Optional free-text description. */
    @Column(name = "descricao", columnDefinition = "TEXT")
    private String description;

    /**
     * 1-based display position inside the course. Named {@code position} because
     * {@code order} is a reserved SQL keyword; the column keeps its legacy name {@code ordem}.
     */
    @Min(1)
    @Column(name = "ordem", nullable = false)
    private Integer position;

    /** Owning course (loaded lazily). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "curso_id", nullable = false)
    @ToString.Exclude
    private Course course;

    /** Identity-based equality: equal only when both instances are persisted with the same id. */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof CourseModule other)) return false;
        return id != null && id.equals(other.id);
    }

    /** Constant class-based hash, stable before and after the id is generated. */
    @Override
    public int hashCode() {
        return getClass().hashCode();
    }
}
