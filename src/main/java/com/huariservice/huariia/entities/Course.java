package com.huariservice.huariia.entities;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.ToString;

/**
 * JPA entity representing a course: the top-level unit of content, composed of
 * {@link CourseModule modules} which in turn contain {@link Lesson lessons}.
 *
 * <p>Mapped to the legacy table {@code cursos}. Indexes on the foreign keys
 * ({@code categoria_id} and {@code autor_id}) speed up the frequent
 * "courses by category" and "courses by author" lookups and joins.</p>
 */
@Entity
@Table(name = "cursos", indexes = {
        @Index(name = "idx_curso_categoria", columnList = "categoria_id"),
        @Index(name = "idx_curso_autor", columnList = "autor_id")
})
@Data
@AllArgsConstructor
@NoArgsConstructor
public class Course {

    /** Surrogate primary key generated by the database. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @ToString.Include
    private Long id;

    /** Unique course title. */
    @Column(name = "titulo", length = 155, nullable = false, unique = true)
    @ToString.Include
    private String title;

    /** Full description shown on the course page. */
    @Column(name = "descricao", columnDefinition = "TEXT", nullable = false)
    private String description;

    /** Unique URL of the course presentation/trailer video. */
    @Column(name = "url_video", length = 254, nullable = false, unique = true)
    private String videoUrl;

    /** Category the course belongs to (loaded lazily). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "categoria_id", nullable = false)
    @ToString.Exclude
    private Category category;

    /** Author/creator of the course (loaded lazily). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "autor_id", nullable = false)
    @ToString.Exclude
    private Author author;

    /** Identity-based equality: equal only when both instances are persisted with the same id. */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Course other)) return false;
        return id != null && id.equals(other.id);
    }

    /** Constant class-based hash, stable before and after the id is generated. */
    @Override
    public int hashCode() {
        return getClass().hashCode();
    }
}
